import mongoose from 'mongoose';
import { MEDIA_KINDS, MEDIA_STATUS } from '@socialhub/shared';
import { jsonPlugin } from './plugins.js';

/**
 * One uploaded image or video of a workspace. The bytes live in object storage under
 * `storageKey`; this document is the record of what was verified there.
 *
 * PENDING_UPLOAD: an upload slot was issued; nothing is known about the object yet.
 * READY:          the object exists, has the declared size and its content matches the type.
 * FAILED:         verification failed (`failureReason`); the object has been removed.
 */
const mediaAssetSchema = new mongoose.Schema(
  {
    workspace: { type: mongoose.Schema.Types.ObjectId, ref: 'Workspace', required: true },
    kind: { type: String, enum: Object.values(MEDIA_KINDS), required: true },
    status: {
      type: String,
      enum: Object.values(MEDIA_STATUS),
      default: MEDIA_STATUS.PENDING_UPLOAD,
    },
    fileName: { type: String, required: true, trim: true },
    mimeType: { type: String, required: true },
    sizeBytes: { type: Number, required: true, min: 1 },
    width: { type: Number },
    height: { type: Number },
    durationSec: { type: Number },
    /**
     * Final object key, generated by the server. No upload link is ever issued for it: the
     * API copies the uploaded object here before verifying it, so a verified file cannot be
     * changed through an upload link.
     */
    storageKey: { type: String, required: true },
    /** Key the browser uploads to. Removed by the clean-up once its link has expired. */
    uploadKey: { type: String },
    /** Set while one completion request is verifying this upload (a short-lived claim). */
    verifyingAt: { type: Date },
    storageDriver: { type: String, required: true },
    failureReason: { type: String },
    uploadedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    /** When the upload slot stops accepting the file. */
    uploadExpiresAt: { type: Date, required: true },
    completedAt: { type: Date },
  },
  { timestamps: true },
);

mediaAssetSchema.index({ workspace: 1, _id: 1 });
// Clean-up of abandoned uploads and unreferenced files.
mediaAssetSchema.index({ status: 1, uploadExpiresAt: 1 });
mediaAssetSchema.index({ status: 1, completedAt: 1 });
mediaAssetSchema.index({ storageKey: 1 }, { unique: true });

jsonPlugin(mediaAssetSchema, {
  hidden: ['storageKey', 'uploadKey', 'verifyingAt', 'storageDriver'],
});

export const MediaAsset =
  mongoose.models.MediaAsset ?? mongoose.model('MediaAsset', mediaAssetSchema);
